function generateCandles(basePrice: number, points: number, volatility: number, trend: number): CandleData[] {
  const candles: CandleData[] = [];
  let currentClose = basePrice * (1 - trend * (points / 100));
  const now = Date.now();
  const stepMs = (24 * 3600 * 1000) / (points / 20);

  for (let i = points - 1; i >= 0; i--) {
    const timestamp = now - i * stepMs;
    const dateObj = new Date(timestamp);
    const timeStr = points <= 30 
      ? dateObj.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }) 
      : dateObj.toLocaleDateString([], { month: 'short', day: 'numeric' });

    const changePercent = (Math.random() - 0.48 + trend * 0.1) * volatility;
    const open = currentClose;
    const close = Math.max(open * (1 + changePercent), open * 0.5);
    const spread = Math.abs(close - open);
    const high = Math.max(open, close) + Math.random() * spread * 0.8;
    const low = Math.min(open, close) - Math.random() * spread * 0.8;
    const volume = Math.floor(10000 + Math.random() * 90000 + (high - low) * 50000);

    candles.push({
      time: timeStr,
      timestamp,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });

    currentClose = close;
  }

  // Adjust last candle to close near basePrice
  if (candles.length > 0) {
    const last = candles[candles.length - 1];
    last.close = basePrice;
    last.high = Math.max(last.high, basePrice);
    last.low = Math.min(last.low, basePrice);
  }

  return candles;
}

function buildCandleMap(basePrice: number, vol: number, trend: number): Record<TimeFrame, CandleData[]> {
  return {
    '1D': generateCandles(basePrice, 38, vol * 0.4, trend * 0.1),
    '5D': generateCandles(basePrice, 45, vol * 0.6, trend * 0.3),
    '1M': generateCandles(basePrice, 30, vol * 0.8, trend * 0.5),
    '3M': generateCandles(basePrice, 60, vol * 1.0, trend * 0.7),
    '6M': generateCandles(basePrice, 60, vol * 1.2, trend * 0.9),
    '1Y': generateCandles(basePrice, 52, vol * 1.5, trend * 1.2),
    '5Y': generateCandles(basePrice, 60, vol * 2.0, trend * 2.0),
    'ALL': generateCandles(basePrice, 70, vol * 2.5, trend * 2.5),
  };
}

function buildSparkline(candles: CandleData[]): number[] {
  return candles.map(c => c.close);
}

